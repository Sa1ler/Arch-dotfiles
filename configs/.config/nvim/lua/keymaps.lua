-- keymaps.lua: Настройка сочетаний клавиш в стиле IDE для Neovim

local map = vim.api.nvim_set_keymap
local opts = { noremap = true, silent = true }

-- ==========================================
-- 1. ВЫДЕЛЕНИЕ ВСЕГО (Ctrl + A)
-- ==========================================
-- В нормальном режиме выделяет весь текст
map('n', '<C-a>', 'ggVG', opts)
-- В визуальном режиме тоже работает
map('v', '<C-a>', 'ggVG', opts)


-- ==========================================
-- 2. КОПИРОВАНИЕ (Ctrl + C)
-- ==========================================
-- Визуальный режим: копирует выделенное в системный буфер
map('v', '<C-c>', '"+y', opts)
-- Нормальный режим: копирует текущую строку
map('n', '<C-c>', '"+yy', opts)


-- ==========================================
-- 3. ВСТАВКА (V в визуальном режиме / Ctrl+V в остальных)
-- ==========================================
-- ТЫ ПРОСИЛ: "вставить на V"
-- В визуальном режиме нажатие 'V' заменит выделение текстом из системного буфера.
-- Это очень удобно: выделил кусок -> нажал V -> он заменился на то, что в буфере.
map('v', 'V', '"+p', opts)

-- В нормальном режиме стандартная IDE-вставка через Ctrl+V
map('n', '<C-v>', '"+p', opts)
-- Во вставочном режиме (Insert) вставляем из системного буфера
map('i', '<C-v>', '<C-r>+', opts)


-- ==========================================
-- 4. ВЫРЕЗАНИЕ (Ctrl + X)
-- ==========================================
-- Визуальный режим: вырезает выделенное в системный буфер
map('v', '<C-x>', '"+d', opts)
-- Нормальный режим: вырезает текущую строку
map('n', '<C-x>', '"+dd', opts)


-- ==========================================
-- 5. УДАЛЕНИЕ (Backspace)
-- ==========================================
-- В Insert-режиме Backspace по умолчанию работает нормально, 
-- но мы гарантируем, что он удаляет символ перед курсором.
map('i', '<BS>', '<BS>', { noremap = false, silent = true })

-- В Normal-режиме Backspace будет работать как 'X' (удаление символа ПОД курсором),
-- чтобы тебе не нужно было переключать раскладку или жать 'x'.
map('n', '<BS>', 'X', opts)

-- В Visual-режиме Backspace удаляет выделенное
map('v', '<BS>', 'd', opts)


-- ==========================================
-- 6. ОТМЕНА И ВОЗВРАТ (Ctrl + Z / Ctrl + Y)
-- ==========================================
-- ⚠️ ВАЖНОЕ ПРИМЕЧАНИЕ ДЛЯ АРХИТЕКТОРА СИСТЕМЫ:
-- Ты написал: "возврат через ctrl v". 
-- Но выше ты же просишь использовать Ctrl+V для вставки! 
-- В любой IDE (VSCode, Sublime) возврат (Redo) — это Ctrl+Y (или Ctrl+Shift+Z).
-- Я настроил Возврат на Ctrl+Y, чтобы не сломать тебе вставку.

-- Отмена (Undo): Ctrl + Z
map('n', '<C-z>', 'u', opts)
map('i', '<C-z>', '<C-o>u', opts) -- <C-o> позволяет выполнить одну команду Normal режима из Insert

-- Возврат (Redo): Ctrl + Y (как в большинстве IDE)
map('n', '<C-y>', '<C-r>', opts)
map('i', '<C-y>', '<C-o><C-r>', opts)


-- ==========================================
-- 7. СОХРАНЕНИЕ (Ctrl + S) - Бонус для IDE
-- ==========================================
-- Без этого IDE-подобной систему не назвать
map('n', '<C-s>', ':w<CR>', opts)
map('i', '<C-s>', '<C-o>:w<CR>', opts)
map('v', '<C-s>', '<Esc>:w<CR>gv', opts) -- Сохранить и вернуть выделение


-- ==========================================
-- 8. ОБЯЗАТЕЛЬНАЯ КАЛИБРОВКА СИСТЕМНОГО БУФЕРА
-- ==========================================
-- Чтобы все эти Ctrl+C / Ctrl+V работали с Hyprland/Quickshell 
-- и другими приложениями, Neovim должен знать о системном буфере.
-- Если у тебя стоит wl-clipboard (для Wayland/Hyprland), добавь это:
vim.opt.clipboard = "unnamedplus"